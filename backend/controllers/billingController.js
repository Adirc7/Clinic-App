const Billing = require('../models/Billing');
const Appointment = require('../models/Appointment');

// ── Admin: Create a new invoice for a completed appointment ──────────────────
exports.createInvoice = async (req, res) => {
  try {
    const { appointmentId, consultationFee, medicineFee, otherCharges, serviceCharge, treatmentCharge, items } = req.body;

    if (!appointmentId) {
      return res.status(400).json({ message: 'Missing required appointmentId.' });
    }

    const appointment = await Appointment.findById(appointmentId);
    if (!appointment) {
      return res.status(404).json({ message: 'Appointment not found.' });
    }
    if (appointment.status === 'Cancelled') {
      return res.status(400).json({ message: 'Cannot bill a cancelled appointment.' });
    }

    // An auto-generated, unpaid bill (created when the doctor completed the visit)
    // is replaced by the admin's itemised bill. Any other existing bill blocks this.
    const existingBill = await Billing.findOne({ appointmentId, isActive: true });
    if (existingBill && !(existingBill.isAutoGenerated && existingBill.status === 'Pending')) {
      return res.status(400).json({ message: 'A bill already exists for this appointment.' });
    }

    // Validate Fees
    const cFee = parseFloat(consultationFee) || 0;
    const mFee = parseFloat(medicineFee) || 0;
    const oFee = parseFloat(otherCharges) || 0;
    const sFee = parseFloat(serviceCharge) || 0;
    const tFee = parseFloat(treatmentCharge) || 0;
    
    if (cFee <= 0 && (!items || items.length === 0)) {
      return res.status(400).json({ message: 'A consultation fee or itemized charge is required.' });
    }

    // Process itemized charges
    const processedItems = (items || []).map(item => ({
      description: item.description?.trim() || 'Additional Service',
      amount: parseFloat(item.amount) || 0
    })).filter(i => i.amount > 0);

    const itemTotal = processedItems.reduce((acc, i) => acc + i.amount, 0);
    // Always compute the total on the server — never trust a client-sent total
    const finalTotal = cFee + mFee + oFee + sFee + tFee + itemTotal;
    if (finalTotal <= 0) {
      return res.status(400).json({ message: 'Total amount must be greater than 0.' });
    }

    const billData = {
      appointmentId,
      // Taken from the appointment so they can't be mismatched by the client
      patientId: appointment.patientId,
      doctorId: appointment.doctorId,
      amount: finalTotal,
      consultationFee: cFee,
      medicineFee: mFee,
      otherCharges: oFee,
      serviceCharge: sFee,
      treatmentCharge: tFee,
      items: processedItems,
      status: 'Pending',
      isAutoGenerated: false,
      isActive: true,
    };

    let invoice;
    if (existingBill) {
      existingBill.set(billData);
      invoice = await existingBill.save();
    } else {
      invoice = await Billing.create(billData);
    }

    // Update appointment status to "Completed" (if it wasn't already) and link the bill
    await Appointment.findByIdAndUpdate(appointmentId, {
      hasBill: true,
      billingId: invoice._id,
      status: 'Completed' 
    });

    const populated = await Billing.findById(invoice._id)
      .populate('appointmentId', 'date time status')
      .populate('patientId', 'name email')
      .populate('doctorId', 'name specialization');

    res.status(201).json(populated);
  } catch (error) {
    res.status(500).json({ message: 'Server error', error: error.message });
  }
};

// ── Admin: Get all invoices ──────────────────────────────────────────────────
exports.getAllInvoices = async (req, res) => {
  try {
    const invoices = await Billing.find({ isActive: true })
      .populate('appointmentId', 'date time status')
      .populate('patientId', 'name email')
      .populate('doctorId', 'name specialization')
      .sort({ createdAt: -1 });
    res.json(invoices);
  } catch (error) {
    res.status(500).json({ message: 'Server error', error: error.message });
  }
};

