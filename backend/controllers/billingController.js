// ── Admin/Patient: Update payment status ────────────────────────────────────
exports.updatePaymentStatus = async (req, res) => {
  try {
    const { status, paymentMethod } = req.body;

    const invoice = await Billing.findById(req.params.id);
    if (!invoice) {
      return res.status(404).json({ message: 'Invoice not found' });
    }

    if (req.user.role !== 'admin') {
      // Patients can only pay their OWN pending bill online (simulated payment)
      const isOwner = req.user.role === 'patient' && invoice.patientId.toString() === req.user._id.toString();
      if (!isOwner) {
        return res.status(403).json({ message: 'Access denied' });
      }
      if (invoice.status !== 'Pending' || status !== 'Paid') {
        return res.status(400).json({ message: 'Only pending bills can be paid.' });
      }
    }

    if (status) invoice.status = status;
    if (paymentMethod) invoice.paymentMethod = paymentMethod;
    if (status === 'Paid') {
      invoice.paidAt = new Date();
      if (!invoice.paymentMethod) invoice.paymentMethod = req.user.role === 'admin' ? 'Cash' : 'Online';
    }

    await invoice.save();

    const updated = await Billing.findById(invoice._id)
      .populate('appointmentId', 'date time status')
      .populate('patientId', 'name email')
      .populate('doctorId', 'name specialization');

    res.json(updated);
  } catch (error) {
    res.status(500).json({ message: 'Server error', error: error.message });
  }
};

// ── Admin: Soft-delete invoice ───────────────────────────────────────────────
exports.deleteInvoice = async (req, res) => {
  try {
    const invoice = await Billing.findById(req.params.id);
    if (!invoice) {
      return res.status(404).json({ message: 'Invoice not found' });
    }

    invoice.isActive = false;
    invoice.status = 'Cancelled';
    await invoice.save();

    // Clear billing flag on appointment
    if (invoice.appointmentId) {
      await Appointment.findByIdAndUpdate(invoice.appointmentId, { hasBill: false, billingId: null });
    }

    res.json({ message: 'Invoice cancelled successfully' });
  } catch (error) {
    res.status(500).json({ message: 'Server error', error: error.message });
  }
};
