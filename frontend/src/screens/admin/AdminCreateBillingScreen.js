import React, { useState, useEffect } from 'react';
import {
  View, Text, StyleSheet, ScrollView, TouchableOpacity,
  TextInput, ActivityIndicator, Alert
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { Ionicons } from '@expo/vector-icons';
import axiosInstance, { getErrorMessage } from '../../api/axiosInstance';

// Defined OUTSIDE the screen component: a component created inside render is a new
// component every keystroke, so the TextInput unmounts and the keyboard closes.
function FeeInput({ label, value, onChange }) {
  return (
    <View style={s.fieldWrap}>
      <Text style={s.fieldLabel}>{label}</Text>
      <View style={s.inputRow}>
        <View style={s.inputPrefix}>
          <Text style={s.prefixText}>Rs.</Text>
        </View>
        <TextInput
          style={s.input}
          value={value}
          onChangeText={onChange}
          keyboardType="decimal-pad"
          placeholder="0"
          placeholderTextColor="#bbb"
        />
      </View>
    </View>
  );
}

export default function AdminCreateBillingScreen({ navigation, route }) {
  // Can be pre-filled from AdminAppointmentList if navigated with params
  const prefill = route?.params || {};

  const [appointments, setAppointments] = useState([]);
  const [selectedApt, setSelectedApt] = useState(
    prefill.appointmentId
      ? { _id: prefill.appointmentId, patientId: prefill.patientId, doctorId: prefill.doctorId }
      : null
  );
  const [showPicker, setShowPicker] = useState(false);
  const [consultationFee, setConsultationFee] = useState('1500');
  const [serviceCharge, setServiceCharge] = useState('0');
  const [treatmentCharge, setTreatmentCharge] = useState('0');
  const [medicineFee, setMedicineFee] = useState('0');
  const [otherCharges, setOtherCharges] = useState('0');
  const [items, setItems] = useState([]); // Array of { description: '', amount: '' }
  const [loading, setLoading] = useState(false);
  const [loadingApts, setLoadingApts] = useState(true);

  const total =
    (parseFloat(consultationFee) || 0) +
    (parseFloat(serviceCharge) || 0) +
    (parseFloat(treatmentCharge) || 0) +
    (parseFloat(medicineFee) || 0) +
    (parseFloat(otherCharges) || 0) +
    items.reduce((acc, item) => acc + (parseFloat(item.amount) || 0), 0);

  useEffect(() => {
    fetchCompletedAppointments();
  }, []);

  const fetchCompletedAppointments = async () => {
    try {
      setLoadingApts(true);
      const res = await axiosInstance.get('/appointments?status=Completed');
      const unbilled = (res.data || []).filter(a => !a.hasBill || (a.billingId?.isAutoGenerated && a.billingId?.status === 'Pending'));
      setAppointments(unbilled);
    } catch (_) {
      Alert.alert('Error', 'Could not load completed appointments.');
    } finally {
      setLoadingApts(false);
    }
  };

  const addItem = () => {
    setItems([...items, { description: '', amount: '' }]);
  };

  const removeItem = (index) => {
    const newItems = items.filter((_, i) => i !== index);
    setItems(newItems);
  };

  const updateItem = (index, key, value) => {
    const newItems = [...items];
    newItems[index][key] = value;
    setItems(newItems);
  };

  const handleSubmit = async () => {
    if (!selectedApt) {
      Alert.alert('Required', 'Please select an appointment.');
      return;
    }
    if (total <= 0) {
      Alert.alert('Invalid', 'Total amount must be greater than 0.');
      return;
    }
    
    // Validate items
    for (let item of items) {
      if (!item.description.trim() || !item.amount.trim()) {
        Alert.alert('Incomplete Items', 'Please provide both description and amount for all itemized charges.');
        return;
      }
    }

    try {
      setLoading(true);
      await axiosInstance.post('/billing', {
        appointmentId: selectedApt._id,
        patientId: selectedApt.patientId?._id || selectedApt.patientId,
        doctorId: selectedApt.doctorId?._id || selectedApt.doctorId,
        consultationFee: parseFloat(consultationFee) || 0,
        serviceCharge: parseFloat(serviceCharge) || 0,
        treatmentCharge: parseFloat(treatmentCharge) || 0,
        medicineFee: parseFloat(medicineFee) || 0,
        otherCharges: parseFloat(otherCharges) || 0,
        items: items.map(item => ({ 
          description: item.description, 
          amount: parseFloat(item.amount) || 0 
        })),
        amount: total,
      });
      Alert.alert('✅ Bill Created', 'The invoice has been created and the patient has been notified.', [
        { text: 'OK', onPress: () => navigation.goBack() },
      ]);
    } catch (error) {
      Alert.alert('Error', getErrorMessage(error, 'Failed to create bill.'));
    } finally {
      setLoading(false);
    }
  };

  return (
    <SafeAreaView style={s.safe}>
      <View style={s.header}>
        <TouchableOpacity onPress={() => navigation.goBack()} style={s.backBtn}>
          <Ionicons name="arrow-back" size={20} color="#0C6875" />
        </TouchableOpacity>
        <Text style={s.headerTitle}>Create Invoice</Text>
        <View style={{ width: 36 }} />
      </View>

      <ScrollView contentContainerStyle={s.scroll} showsVerticalScrollIndicator={false}>

        {/* Appointment Selector */}
        <Text style={s.sectionLabel}>Select Appointment</Text>
        <TouchableOpacity style={s.selector} onPress={() => setShowPicker(p => !p)}>
          <Ionicons name="calendar-outline" size={18} color="#0C6875" />
          <Text style={[s.selectorText, !selectedApt && { color: '#bbb' }]}>
            {selectedApt
              ? `${selectedApt.patientName || selectedApt.patientId?.name || 'Patient'} · ${new Date(selectedApt.date).toLocaleDateString()} · ${selectedApt.time}`
              : 'Choose a completed appointment...'}
          </Text>
          <Ionicons name={showPicker ? 'chevron-up' : 'chevron-down'} size={16} color="#999" />
        </TouchableOpacity>

        {showPicker && (
          <View style={s.pickerList}>
            {loadingApts ? (
              <ActivityIndicator color="#0C6875" style={{ padding: 20 }} />
            ) : appointments.length === 0 ? (
              <Text style={s.pickerEmpty}>No unbilled completed appointments found.</Text>
            ) : (
              appointments.map(apt => (
                <TouchableOpacity
                  key={apt._id}
                  style={[s.pickerItem, selectedApt?._id === apt._id && s.pickerItemSelected]}
                  onPress={() => {
                    setSelectedApt(apt);
                    // Start from this doctor's own consultation fee
                    if (apt.doctorId?.consultationFee != null) setConsultationFee(String(apt.doctorId.consultationFee));
                    setShowPicker(false);
                  }}
                >
                  <Text style={s.pickerItemName}>{apt.patientName || apt.patientId?.name}</Text>
                  <Text style={s.pickerItemSub}>
                    Dr. {apt.doctorId?.name || '—'} · {new Date(apt.date).toLocaleDateString()} · {apt.time}
                  </Text>
                </TouchableOpacity>
              ))
            )}
          </View>
        )}

        {/* Patient / Doctor info (auto-filled) */}
        {selectedApt && (
          <View style={s.infoCard}>
            <View style={s.infoRow}>
              <Ionicons name="finger-print-outline" size={15} color="#0C6875" />
              <Text style={s.infoLabel}>Appt ID:</Text>
              <Text style={s.infoValue} numberOfLines={1}>{selectedApt._id}</Text>
            </View>
            <View style={s.infoRow}>
              <Ionicons name="person-outline" size={15} color="#0C6875" />
              <Text style={s.infoLabel}>Patient:</Text>
              <View style={{ flex: 1 }}>
                <Text style={s.infoValue}>{selectedApt.patientName || selectedApt.patientId?.name}</Text>
                <Text style={s.idSubText}>ID: {selectedApt.patientId?._id || selectedApt.patientId}</Text>
              </View>
            </View>
            <View style={s.infoRow}>
              <Ionicons name="medical-outline" size={15} color="#0C6875" />
              <Text style={s.infoLabel}>Doctor:</Text>
              <Text style={s.infoValue}>Dr. {selectedApt.doctorId?.name || '—'}</Text>
            </View>
          </View>
        )}

        {/* Fee Breakdown */}
        <Text style={s.sectionLabel}>Fee Breakdown</Text>
        <FeeInput label="Consultation Fee *" value={consultationFee} onChange={setConsultationFee} />
        <FeeInput label="Service Charge" value={serviceCharge} onChange={setServiceCharge} />
        <FeeInput label="Treatment Charge" value={treatmentCharge} onChange={setTreatmentCharge} />
        <FeeInput label="Medicine Fee" value={medicineFee} onChange={setMedicineFee} />
        <FeeInput label="Other Charges" value={otherCharges} onChange={setOtherCharges} />

        {/* Dynamic Items */}
        <View style={s.sectionHeader}>
          <Text style={s.sectionLabel}>Itemized Charges</Text>
          <TouchableOpacity style={s.addBtn} onPress={addItem}>
            <Ionicons name="add-circle" size={18} color="#0C6875" />
            <Text style={s.addBtnText}>Add Item</Text>
          </TouchableOpacity>
        </View>

        {items.map((item, index) => (
          <View key={index} style={s.itemRow}>
            <TextInput
              style={[s.input, s.itemDesc]}
              placeholder="Description (e.g. Lab Test)"
              value={item.description}
              onChangeText={(text) => updateItem(index, 'description', text)}
            />
            <TextInput
              style={[s.input, s.itemAmount]}
              placeholder="Amount"
              value={item.amount}
              onChangeText={(text) => updateItem(index, 'amount', text)}
              keyboardType="decimal-pad"
            />
            <TouchableOpacity onPress={() => removeItem(index)}>
              <Ionicons name="trash-outline" size={20} color="#FF3B30" />
            </TouchableOpacity>
          </View>
        ))}

        {/* Total */}
        <View style={s.totalCard}>
          <Text style={s.totalLabel}>Total Amount</Text>
          <Text style={s.totalValue}>Rs. {total.toFixed(2)}</Text>
        </View>

        {/* Submit */}
        <TouchableOpacity style={s.submitBtn} onPress={handleSubmit} disabled={loading}>
          {loading ? (
            <ActivityIndicator color="#fff" />
          ) : (
            <>
              <Ionicons name="receipt-outline" size={18} color="#fff" />
              <Text style={s.submitText}>Generate Invoice</Text>
            </>
          )}
        </TouchableOpacity>

        <View style={{ height: 40 }} />
      </ScrollView>
    </SafeAreaView>
  );
}

